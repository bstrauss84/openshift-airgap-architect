#!/usr/bin/env node
"use strict";

/**
 * Generates docs/minor-release/ARCHITECTURE_EVIDENCE_LEDGER.md from the two
 * canonical authorities.
 *
 * WHY GENERATED. The human asked for the exact html-single URL evidence to live
 * in the repository so the research never has to be reconstructed. A hand-written
 * ledger would drift from `data/arch-support/` and `data/scenario-support/` the
 * first time a disposition changed, and a stale evidence document is worse than
 * none — it looks authoritative. This reads the data the validators enforce, so
 * the ledger cannot disagree with them.
 *
 * Usage:
 *   node scripts/gen-architecture-evidence-ledger.js            write the file
 *   node scripts/gen-architecture-evidence-ledger.js --check    fail if stale
 */

const fs = require("fs");
const path = require("path");

const REPO_ROOT = path.resolve(__dirname, "..");
const OUT = path.join(REPO_ROOT, "docs", "minor-release", "ARCHITECTURE_EVIDENCE_LEDGER.md");

const BASE = "https://docs.redhat.com/en/documentation/openshift_container_platform/%M/html-single/%B";
const BOOKS = [
  ["installation_overview", "Installation overview"],
  ["installing_on_bare_metal", "Installing on bare metal"],
  ["installing_on_vmware_vsphere", "Installing on VMware vSphere"],
  ["installing_on_nutanix", "Installing on Nutanix"],
  ["installing_on_aws", "Installing on AWS"],
  ["installing_on_azure", "Installing on Azure"],
  ["installing_on_ibm_cloud", "Installing on IBM Cloud"],
  ["installing_an_on-premise_cluster_with_the_agent-based_installer", "Installing an on-premise cluster with the Agent-based Installer"],
];

const url = (m, b) => BASE.replace("%M", m).replace("%B", b);
const cell = (s, n = 190) => {
  const t = String(s || "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
  return t.length > n ? `${t.slice(0, n - 3)}...` : t;
};
const readJson = (p) => JSON.parse(fs.readFileSync(p, "utf8"));

function build(root, minors) {
  const L = [];
  const w = (s = "") => L.push(s);

  w("# Architecture and scenario evidence ledger");
  w("");
  w("**Generated by** `scripts/gen-architecture-evidence-ledger.js` from");
  w("`data/arch-support/<minor>.json` and `data/scenario-support/<minor>.json`.");
  w("Do not hand-edit — change the data and regenerate, so the ledger cannot drift away");
  w("from what the validators enforce. `npm run check:evidence-ledger` fails if it is stale.");
  w("");
  w("Every URL below was fetched and parsed locally (HTTP 200). Summarising fetchers were");
  w("deliberately not used: an earlier pass in this project produced a fabricated support");
  w("table that way, so all claims here come from literal page text.");
  w("");
  w("Precedence rules for conflicting sources: [`EVIDENCE_SOURCE_PRECEDENCE.md`](./EVIDENCE_SOURCE_PRECEDENCE.md).");
  w("");
  w("## 1. Source URLs consulted");
  w("");
  w("| minor | document title | html-single URL |");
  w("|---|---|---|");
  for (const m of minors) for (const [b, t] of BOOKS) w(`| ${m} | ${t} | \`${url(m, b)}\` |`);
  w("");
  w(`${minors.length * BOOKS.length} documents.`);
  w("");

  w("## 2. Architecture cells — upstream vs Architect");
  w("");
  w("`upstreamSupport` is what Red Hat documents. `offered` is what Architect exposes.");
  w("They are allowed to differ; a narrowing requires an explicit `oaaScopeDecision`.");
  w("");
  for (const m of minors) {
    const d = readJson(path.join(root, "data", "arch-support", `${m}.json`));
    w(`### OpenShift ${m}`);
    w("");
    w("| scenario | arch | upstream | Architect | offered | governing evidence |");
    w("|---|---|---|---|---|---|");
    for (const r of d.matrix) {
      for (const [a, c] of Object.entries(r.architectures)) {
        w(`| \`${r.scenarioId}\` | ${a} | **${c.upstreamSupport}** | ${c.disposition} | ${String(c.offered)} | ${cell(c.upstreamReason)} |`);
      }
    }
    w("");
  }

  w("## 3. Platform x installation-method cells");
  w("");
  for (const m of minors) {
    const d = readJson(path.join(root, "data", "scenario-support", `${m}.json`));
    w(`### OpenShift ${m}`);
    w("");
    w("| platform | method | upstream | Architect | scenarioId |");
    w("|---|---|---|---|---|");
    for (const r of d.matrix) {
      w(`| ${r.platform} | ${r.method} | **${r.upstream}** | ${r.oaa} | ${r.scenarioId || "—"} |`);
    }
    w("");
  }

  w("## 4. Cells that are not a simple agreement");
  w("");
  w("Everything below is deliberate and recorded. None of it is a defect: Architect");
  w("fails closed wherever Red Hat has not clearly said yes.");
  w("");
  w("| minor | cell | upstream | Architect | why |");
  w("|---|---|---|---|---|");
  for (const m of minors) {
    const d = readJson(path.join(root, "data", "arch-support", `${m}.json`));
    for (const r of d.matrix) {
      for (const [a, c] of Object.entries(r.architectures)) {
        if (c.upstreamSupport !== "unsupported" && c.offered === false) {
          w(`| ${m} | \`${r.scenarioId}\` / ${a} | ${c.upstreamSupport} | not offered | ${cell(c.oaaScopeDecision || c.upstreamReason, 230)} |`);
        }
      }
    }
    const s = readJson(path.join(root, "data", "scenario-support", `${m}.json`));
    for (const r of s.matrix) {
      if (["supported", "documentation-conflict"].includes(r.upstream) && !r.oaa.startsWith("modelled")) {
        w(`| ${m} | ${r.platform} / ${r.method} | ${r.upstream} | ${r.oaa} | ${cell(r.oaaReason, 230)} |`);
      }
    }
  }
  // No trailing `w("")`. The joined lines already get exactly one closing
  // newline below. Pushing an empty element produced a trailing BLANK line,
  // which `git diff --check` reports as a whitespace defect — and which was
  // the actual cause of the "ledger out of date" gate failure at 21529ae: the
  // canonical inputs had not changed and the committed content was correct,
  // the GENERATOR had drifted by one blank line and so disagreed with its own
  // committed output forever.
  return `${L.join("\n")}\n`;
}

if (require.main === module) {
  const { getSupportedMinors } = require("./lib/supported-minors");
  getSupportedMinors()
    .then((minors) => {
      const text = build(REPO_ROOT, minors);
      if (process.argv.includes("--check")) {
        const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
        if (current !== text) {
          console.error(
            "Architecture evidence ledger is out of date — run `npm run gen:evidence-ledger`.\n" +
              "  The ledger is generated from data/arch-support and data/scenario-support so it cannot\n" +
              "  drift from the dispositions the validators enforce."
          );
          process.exit(1);
        }
        console.log(`Architecture evidence ledger is in sync (${minors.length} minor(s)).`);
        process.exit(0);
      }
      fs.writeFileSync(OUT, text);
      console.log(`Wrote ${path.relative(REPO_ROOT, OUT)} (${minors.length} minor(s), ${BOOKS.length} books each).`);
      process.exit(0);
    })
    .catch((err) => {
      console.error(`Could not read the supported-minor list: ${err.message}`);
      process.exit(1);
    });
}

module.exports = { build, BOOKS, url };
